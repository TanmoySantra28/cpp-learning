#include <iostream>
int main() {

  // integer
  int age = 23;
  int year = 2027;

  std::cout << age << year << '\n';

  // double
  double gpa = 7.23;
  double price = 25.77;

  std::cout << gpa << price << '\n';

  // character
  char grade = 'A';
  char currency = '$';

  std::cout << grade << currency << '\n';

  // boolean
  bool isStudent = false;
  bool onSwitch = true;

  std::cout << isStudent << onSwitch << '\n';

  // string
  std::string name = "Tanmoy";
  std::string city = "Kolkata";

  std::cout << name << " lives in " << city << '\n';
}
